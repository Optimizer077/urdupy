_PREFIX = "اصل_"
_TEXT_PREFIX = "متن_"
_URDU_DIGITS = "۰۱۲۳۴۵۶۷۸۹"
_TO_URDU_DIGITS = str.maketrans("0123456789", _URDU_DIGITS)
_TO_ASCII_DIGITS = str.maketrans(_URDU_DIGITS, "0123456789")


def _valid_identifier(name):
    return name.isidentifier() and not keyword.iskeyword(name)


def encode_identifier(name):
    """Return a reversible Urdu-only spelling for a Python identifier.

    Dotted paths are encoded one identifier at a time. Python keywords cannot be
    API identifiers in normal source and are rejected. Unicode source spelling
    is retained exactly; this helper does not silently apply normalization.
    """
    if not isinstance(name, str):
        raise TypeError("identifier must be a string")
    if not _valid_identifier(name):
        raise ValueError("expected one valid Python identifier, not a dotted path or keyword")
    return _PREFIX + "_".join(str(ord(character)).translate(_TO_URDU_DIGITS) for character in name)


def encode_text(text):
    """Losslessly spell any string using Urdu digits, with the ``متن_`` prefix.

    Unlike identifiers, literal text may be empty, contain dots, spaces, NUL or
    even lone surrogate codepoints. The result itself is safe UTF-8 text.
    """
    if not isinstance(text, str):
        raise TypeError("text must be a string")
    return _TEXT_PREFIX + "_".join(str(ord(character)).translate(_TO_URDU_DIGITS) for character in text)


def decode_text(alias):
    """Decode an encoded literal string; return None for noncanonical input."""
    if not isinstance(alias, str) or not alias.startswith(_TEXT_PREFIX):
        return None
    body = alias[len(_TEXT_PREFIX):]
    if not body:
        return ""
    characters = []
    for part in body.split("_"):
        if not part or len(part) > 7 or any(digit not in _URDU_DIGITS for digit in part):
            return None
        if len(part) > 1 and part[0] == _URDU_DIGITS[0]:
            return None
        point = int(part.translate(_TO_ASCII_DIGITS))
        if point > 0x10FFFF:
            return None
        characters.append(chr(point))
    return "".join(characters)


def decode_identifier(alias):
    """Decode canonical ``اصل_…`` spellings; return None for all other input.

    Malformed or out-of-range codepoints, ASCII/mixed digits, leading zeroes,
    surrogate characters and decoded nonidentifiers are never accepted. A
    reserved-looking but malformed name remains a normal user identifier.
    """
    if not isinstance(alias, str) or not alias.startswith(_PREFIX):
        return None
    encoded = alias[len(_PREFIX):].split("_")
    characters = []
    for part in encoded:
        if not part or len(part) > 7 or any(digit not in _URDU_DIGITS for digit in part):
            return None
        if len(part) > 1 and part[0] == _URDU_DIGITS[0]:
            return None
        point = int(part.translate(_TO_ASCII_DIGITS))
        if point > 0x10FFFF or 0xD800 <= point <= 0xDFFF:
            return None
        characters.append(chr(point))
    name = "".join(characters)
    return name if _valid_identifier(name) else None


def canonical_name(name):
    """Resolve a member/protocol/built-in spelling, preserving unknown names.

    Module paths and immutable values have separate namespaces and must be
    resolved by their respective catalog dictionaries.
    """
    if not isinstance(name, str):
        raise TypeError("name must be a string")
    for aliases in (MEMBER_ALIASES, PROTOCOL_ALIASES, BUILTIN_NAMES):
        if name in aliases:
            return aliases[name]
    return decode_identifier(name) or name


def urdu_name(name):
    """Return the preferred curated spelling, or encode an unknown identifier.

    Module names are considered first. A dotted backend path can have a curated
    module alias (for example matplotlib.pyplot); other dotted paths should be
    processed segment by segment by callers.
    """
    if not isinstance(name, str):
        raise TypeError("name must be a string")
    for aliases in (MODULE_ALIASES, MEMBER_ALIASES, PROTOCOL_ALIASES, BUILTIN_NAMES):
        for alias, original in aliases.items():
            if original == name:
                return alias
    return encode_identifier(name)


def vocabulary():
    """Return an independent, grouped inventory for help and discovery tools."""
    return {
        "modules": MODULE_ALIASES.copy(),
        "members": MEMBER_ALIASES.copy(),
        "builtins": BUILTIN_NAMES.copy(),
        "values": VALUE_ALIASES.copy(),
        "protocols": PROTOCOL_ALIASES.copy(),
    }
